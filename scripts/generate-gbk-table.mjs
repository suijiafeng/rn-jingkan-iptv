// Writes src/domain/gbkTable.ts from Node's WHATWG GBK decoder (ICU).
// Hermes on Android ships only a UTF-8 TextDecoder, so the app carries this
// static two-byte table. Run: node scripts/generate-gbk-table.mjs
import { writeFileSync } from "node:fs";

const decoder = new TextDecoder("gbk", { fatal: true });
if (
  decoder.decode(new Uint8Array([0xa2, 0xe3])) !== "€" ||
  decoder.decode(new Uint8Array([0xa8, 0xbc])) !== "ḿ"
) {
  throw new Error(
    "This ICU uses legacy CP936 mappings; use the documented Node 24.19.0 runtime (ICU 78+) to regenerate the WHATWG table.",
  );
}
const rows = [];
for (let lead = 0x81; lead <= 0xfe; lead += 1) {
  let row = "";
  for (let trail = 0x40; trail <= 0xfe; trail += 1) {
    if (trail === 0x7f) continue;
    const text = decoder.decode(new Uint8Array([lead, trail]));
    if (text.length !== 1) throw new Error(`unexpected ${lead}/${trail}`);
    const code = text.charCodeAt(0);
    // Private-use and anything outside plain CJK text stays escaped.
    row +=
      code >= 0x3000 && code < 0xe000
        ? text
        : `\\u${code.toString(16).padStart(4, "0")}`;
  }
  rows.push(`  "${row}",`);
}
const source = `// Generated by scripts/generate-gbk-table.mjs from Node's WHATWG GBK decoder.
// One string per lead byte 0x81–0xFE; each holds the 190 characters for trail
// bytes 0x40–0x7E then 0x80–0xFE. Do not edit by hand.
export const GBK_TRAIL_COUNT = 190;
export const GBK_ROWS: readonly string[] = [
${rows.join("\n")}
];
`;
writeFileSync(new URL("../src/domain/gbkTable.ts", import.meta.url), source);
console.log(`wrote ${rows.length} rows`);
